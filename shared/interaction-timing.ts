/**
 * interaction-timing.ts — 交互节拍常量（单一真源）
 *
 * 背景（审计 A-4 / C 清单 #7）：正文自动保存过去有三套节拍 ——
 * 协同写作视图 2000ms、单元写作台 800ms、场景细纲 1000ms。
 * 三者都是「停止输入后写盘」的防抖，语义完全一致，只是各写各的数字，
 * 于是同一个动作在不同视图的手感不一样，改一处也不知道还有两处。
 *
 * 收敛口径：
 * - 只收「正文类自动保存」这一种节拍；节流/轮询/动画时长各有语义，不并入。
 * - 取 1000ms：协同的 2000ms 在切章前显得迟钝（切章要等 2s 才落盘），
 *   单元写作的 800ms 又偏频繁；1000ms 与场景细纲既有值一致，行为变化面最小。
 */

/** 正文自动保存的防抖节拍（毫秒）：协同写作 / 单元写作 / 场景细纲共用 */
export const AUTOSAVE_DELAY_MS = 1000;

/**
 * 「保存成功」反馈的展示时长（毫秒）。
 *
 * 审计 A-2 / A-13：协同写作是 3000ms、单元写作是 1500ms，同一个动作两种手感。
 * 取 1500：保存是高频、低信息量反馈，3 秒会盖住后续操作。
 */
export const SAVE_FEEDBACK_MS = 1500;

/**
 * Notice（浮层提示）展示时长规范（毫秒）。
 *
 * 背景（审计 A-11 / C 清单 #13）：全仓 Notice 时长散布八种取值
 * （5000×86、6000×58、3000×52、8000×80 …），同语义消息在不同视图停留时间不同。
 * 收敛为四档语义，新代码必须引用本表，不再写裸数字：
 *
 * - `short`：纯确认类（已复制/已保存），扫一眼即可
 * - `normal`：默认，一句话结果
 * - `long`：错误与需要处置的告警（含路径、密钥、失败原因）
 * - `sticky`：常驻，直到用户手动关闭（进度类，必须自己负责隐藏）
 */
export const NOTICE_MS = {
    /** 纯确认类提示，2000ms */
    short: 2000,
    /** 默认提示，4000ms */
    normal: 4000,
    /** 错误/需处置告警，8000ms */
    long: 8000,
    /** 常驻不自动消失，由调用方隐藏 */
    sticky: 0,
} as const;
