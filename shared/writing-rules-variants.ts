/**
 * shared/writing-rules-variants.ts — 写作规则的「不同思路」版本（3.7 / 3.8 / 3.9）
 *
 * 背景：3.6.0（现状）与人味块存在 12 条正面对冲（一句一段、精确数字禁令、压缩包说冷…），
 * 而 R1 消融证明「只删冲突不立锚点」会让文本更碎（短叙述占比反而 0.74）。所以这里给的是
 * 三种「有主张」的写法，而不是删减版：
 *
 *   3.7.0-anchor      正向锚点：只写「怎么写」的正例，段落只留一条硬规则
 *   3.8.0-scene-beat  场景节拍：一场戏 = 一次交换（目标/阻碍/交换/变化），叙述只写镜头能拍到的
 *   3.9.0-voiceprint  真人特征：只描述真人文本长什么样（八条可观察特征），不列禁止清单
 *
 * 三个版本都保持 `## 一、…` 编号章 + `### ` 子节结构，与既有解析逻辑兼容。
 */

export interface BuiltinRuleVariant {
    /** 版本号（同时作为 id 后缀：`builtin:<version>`） */
    version: string;
    content: string;
    notes: string;
}

/** 3.7.0 —— 正向锚点版：用「写成什么样」替代「不许怎样」 */
export const WRITING_RULES_ANCHOR = `# 网络小说写作规则（正向锚点版）

> 这一版只给「怎么写」的正例，不列禁止清单。照做就有节奏；做不到也不必逐条自证。

## 一、段落——唯一的段落规则

- 每个自然段 2–6 句、80–220 字。允许一句成段，但整章不超过 5 处。
- 不要一句一段，也不要把「一个句号」当成一次断行。
- 一个自然段推进一个动作单元：一个动作 + 一个反应 + 一句对话，或一个动作 + 一段观察。

## 二、对话——信息由人物说出来

- 对话占全章三成以上。凡是人物能开口讲的信息，写成对话，不要由叙述者转述。
- 一场戏至少 6–10 个来回；允许抢话、打断、答非所问、重复。
- 对话标签优先用「说」「问」「答」，或直接裸对话；不堆「愤怒地说」这类副词标签。

## 三、句子——长短混用

- 短句用来跑节奏，每隔几句要有一个能连着读下去的长句。
- 不要整章都是 10–20 字的均匀句；句长在 8–40 字之间波动。
- 允许重复用词、口语、半截话；词汇过于「正确」本身就是机器痕迹。

## 四、细节——写身体，不写形容词

- 情绪落到身体上：冷、热、麻、紧、酸、抖、耳鸣、口干。
- 用具体时间与序数定节拍：第几分钟、第几次、第几波、第几手。
- 一个场景 2–3 处关键感觉即可，放在动作或转折上，不要逐段打卡。

## 五、收尾

- 段末不写总结句、升华句、作者点评。
- 章末落在动作、对话，或一句没说完的话上。

## 六、格式参考

- 章标题单独一行：## 第N章 章名。
- 对话用中文双引号「」或“”，同一章统一。
- 场景切换空一行；不用分隔线、不用小标题分节。
- 省略号、破折号全文各不超过 2 处；不用分号。

## 七、动笔前默念

1. 这一场谁想要什么，谁在拦。
2. 这句话能不能让人物自己说出口。
3. 这一段能不能合成一个自然段。
`;

/** 3.8.0 —— 场景节拍版：把「一场戏」当最小单位 */
export const WRITING_RULES_SCENE_BEAT = `# 网络小说写作规则（场景节拍版）

> 以「一场戏」为单位写作。句子、段落都服从这场戏的节拍，而不是反过来。

## 一、一场戏 = 一次交换

每场戏都要能填这四格：

- 谁要什么
- 谁或什么在拦
- 交换了什么：信息、让步、威胁、承诺、代价
- 离场时谁变了

填不出来，说明这场戏没有戏——合并或删掉。

## 二、三段式推进

### 入场

1–3 句落地：具体地点、时间或光线、一个感官细节。不要先讲背景。

### 交锋

对话为主，至少 6 个来回；每一次来回都要推进上面某一格。允许答非所问、抢话、沉默。

### 收束

停在一个动作、一个决定，或一句没有回答的问题上。不总结、不升华。

## 三、叙述只写镜头能拍到的

- 写动作、表情、声音、温度、触感、位置变化。
- 不写「他心里明白」「气氛凝重」这类镜头拍不到的东西；要写就让人物说出来，或让身体先反应。
- 环境只写与当前冲突有关的那一部分。

## 四、对话承担信息

- 背景、来历、规则、恩怨，尽量让角色在对话里说出来。
- 对话标签用「说」「问」「答」或裸对话；不堆副词。
- 一个人说话要有自己的口头禅和断句习惯。

## 五、段落随动作单元

- 自然段 2–6 句、80–220 字；一个动作单元一段。
- 不一句一段，不每段一句号断行。
- 对话可以与动作同段；连续三条以上纯对话时可以单独成段。

## 六、时间与地点必须落地

- 每场戏开头给一个时间锚点：第几分钟、第几波、第几次、三天后。
- 场景之间必须写清过渡：怎么到的、过了多久、光线变没变。

## 七、格式参考

- 章标题单独一行：## 第N章 章名。
- 对话用中文双引号「」或“”，同一章统一。
- 场景切换空一行；不用分隔线、不用小标题分节。
- 省略号、破折号全文各不超过 2 处；不用分号。
`;

/** 3.9.0 —— 真人特征版：只描述结果长什么样，不列禁止清单 */
export const WRITING_RULES_VOICEPRINT = `# 网络小说写作规则（真人特征版）

> 这一版不写「不要做什么」，只描述真人写的文本长什么样。写成这样就够了，不要当成指标清单逐项打勾。

## 一、真人文本的八个可观察特征

1. 短叙述占一半以上：25 字以内的叙述句占 50%–65%；但不是整章碎句——每 3–5 个短句之后必有一个长句。
2. 对话占三成以上，对话块每千字 25 个以上；很多信息是人物自己说出来的，不是叙述者交代的。
3. 口语标记每千字 2 个以上：好家伙、晓得、啥、咋、呗、嘛、得了、行吧、算了、顶不住、扛不住。
4. 时间锚点全章 6 处以上：第几分钟、第几次、第几波、三天后、去年冬天。
5. 段落 2–6 句、80–220 字，有长有短，不一句一段。
6. 句长在 8–40 字之间波动，不出现连续三段相同句式开头。
7. 允许重复用词、口头禅、半截话、答非所问；人物说话不必语法正确。
8. 结尾落在动作、对话或一句没说完的话上；不总结、不升华。

## 二、怎么写出来

### 先写台词

先把这一场人物要说的台词写出来，包括打断、重复、废话。台词承担信息。

### 再补叙述

在台词之间补动作、反应、感官；每两三条对话之间最多 1–3 句叙述。

### 段落跟着动作单元

一个动作单元一个自然段，2–6 句；不要一句一段。

## 三、格式参考

- 章标题单独一行：## 第N章 章名。
- 对话用中文双引号「」或“”，同一章统一。
- 场景切换空一行；不用分隔线、不用小标题分节。
- 省略号、破折号全文各不超过 2 处；不用分号。
`;

