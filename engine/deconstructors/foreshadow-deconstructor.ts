/**
 * 伏笔类型：物品/功法/人物/设定/事件。
 */
export type ForeshadowType = 'item' | 'skill' | 'character' | 'setting' | 'event';

/**
 * 伏笔条目：名称、类型、埋设/计划回收章节、状态等。
 */
export interface Foreshadow {
    id: string;
    name: string;
    type: ForeshadowType;
    description: string;
    firstAppearance: {
        position: number;
        paragraphIndex: number;
        excerpt: string;
    };
    importantAppearances: Array<{
        position: number;
        paragraphIndex: number;
        excerpt: string;
        description?: string;
    }>;
    totalAppearances: number;
    importance: number;
    resolution?: {
        position: number;
        paragraphIndex: number;
        excerpt: string;
        description: string;
    };
    isNoise?: boolean;
    semanticVerification?: {
        categoryScores: Record<ForeshadowType, number>;
        verifiedType: ForeshadowType;
        confidence: number;
    };
}

/**
 * 语义相近的伏笔对（用于合并/去重）。
 */
export interface SemanticForeshadowPair {
    setupParagraph: string;
    payoffParagraph: string;
    setupParagraphIndex: number;
    payoffParagraphIndex: number;
    score: number;
    confidence: 'high' | 'medium';
}

/**
 * 伏笔质量评分（埋设/回收/关联度）。
 */
export interface ForeshadowQualityScore {
    totalScore: number;
    diversityScore: number;
    resolutionRate: number;
    signalNoiseRatio: number;
    coverageScore: number;
}

/**
 * 伏笔配对结果（埋设 ↔ 回收）。
 */
export interface ForeshadowPair {
    id: string;
    setupForeshadowId: string;
    setupForeshadowName: string;
    payoffForeshadowId?: string;
    payoffForeshadowName?: string;
    pairType: 'one-to-one' | 'one-to-many' | 'many-to-one';
    confidence: number;
    matchDimensions: {
        entityMatch: number;
        semanticMatch: number;
        temporalMatch: number;
        typeMatch: number;
    };
    setupDescription?: string;
    payoffDescription?: string;
    setupChapter?: number;
    payoffChapter?: number;
    quality?: ResolutionQuality;
}

/**
 * 伏笔回收质量评估。
 */
export interface ResolutionQuality {
    overallScore: number;
    completeness: number;
    timing: number;
    method: 'climax' | 'gradual' | 'twist' | 'unknown';
    methodScore: number;
    emotionalImpact: number;
    buildupSufficiency: number;
    suggestions: string[];
    lowQuality: boolean;
}

/**
 * 世界观设定分类。
 */
export type WorldbuildingCategory =
    | 'geography'
    | 'history'
    | 'politics'
    | 'economy'
    | 'culture'
    | 'religion'
    | 'magic_system'
    | 'race'
    | 'technology'
    | 'organization';

/**
 * 单条世界观设定。
 */
export interface WorldbuildingEntry {
    category: WorldbuildingCategory;
    name: string;
    description: string;
    firstMention: number;
    mentionCount: number;
    chapters: number[];
    relatedEntries: string[];
}

/**
 * 世界观拆解结果。
 */
export interface WorldbuildingResult {
    entries: WorldbuildingEntry[];
    categoryDistribution: Record<WorldbuildingCategory, number>;
    totalEntries: number;
    coverageScore: number;
    description: string;
}

/**
 * 设定密度分段统计。
 */
export interface SettingDensitySegment {
    chapterIndex: number;
    position: number;
    density: number;
    newSettings: number;
    repeatedSettings: number;
    overload: boolean;
}

/**
 * 设定密度分析结果。
 */
export interface SettingDensityResult {
    segments: SettingDensitySegment[];
    avgDensity: number;
    maxDensity: number;
    minDensity: number;
    overloadChapters: number[];
    avgNewSettingsPerChapter: number;
    densityTrend: 'increasing' | 'decreasing' | 'stable';
    distributionScore: number;
    description: string;
}

/**
 * 伏笔网络分析（节点/边/中心度）。
 */
export interface ForeshadowNetworkAnalysis {
    mainlineForeshadows: string[];
    sidelineForeshadows: string[];
    hierarchy: Array<{
        level: 'core' | 'secondary' | 'tertiary';
        foreshadowId: string;
        foreshadowName: string;
        children: string[];
    }>;
    chains: Array<{
        chainId: string;
        foreshadowIds: string[];
        description: string;
    }>;
    convergences: Array<{
        position: number;
        foreshadowIds: string[];
        description: string;
    }>;
    densityByChapter: Array<{
        chapter: number;
        setupCount: number;
        payoffCount: number;
        totalCount: number;
    }>;
    rhythmBalance: {
        setupRate: number;
        payoffRate: number;
        balanceScore: number;
        isBalanced: boolean;
    };
}

/**
 * 未回收伏笔条目。
 */
export interface UnresolvedForeshadow {
    id: string;
    name: string;
    type: ForeshadowType;
    importance: number;
    plantedChapter: number;
    plantedPosition: number;
    chaptersSincePlanted: number;
    lastMentionChapter: number;
    isForgotten: boolean;
    suggestedRecallChapter: number;
    urgency: 'high' | 'medium' | 'low';
}

/**
 * 未回收伏笔追踪结果。
 */
export interface UnresolvedTracker {
    totalUnresolved: number;
    byImportance: UnresolvedForeshadow[];
    byAge: UnresolvedForeshadow[];
    forgottenForeshadows: UnresolvedForeshadow[];
    recallSuggestions: Array<{
        chapter: number;
        foreshadows: string[];
        reason: string;
    }>;
}

/**
 * 增强版伏笔分析（含语义与网络）。
 */
export interface EnhancedForeshadowAnalysis extends ForeshadowAnalysisResult {
    pairs?: ForeshadowPair[];
    networkAnalysis?: ForeshadowNetworkAnalysis;
    unresolvedTracker?: UnresolvedTracker;
    resolutionQualityStats?: {
        avgQuality: number;
        qualityDistribution: { excellent: number; good: number; fair: number; poor: number };
        lowQualityCount: number;
    };
}

/**
 * 伏笔分析汇总结果。
 */
export interface ForeshadowAnalysisResult {
    foreshadows: Foreshadow[];
    typeDistribution: Record<ForeshadowType, number>;
    stats: {
        totalForeshadows: number;
        resolvedCount: number;
        unresolvedCount: number;
        avgImportance: number;
    };
    timeline: Array<{
        position: number;
        type: 'setup' | 'payoff' | 'reference';
        foreshadowId: string;
        foreshadowName: string;
        excerpt: string;
    }>;
    semanticPairs?: SemanticForeshadowPair[];
    qualityScore?: ForeshadowQualityScore;
    worldbuilding?: WorldbuildingResult;
    settingDensity?: SettingDensityResult;
}

