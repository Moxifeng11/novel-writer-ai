/**
 * priority-system.ts — L0-L3 优先级仲裁体系（2026-11-25，借鉴云笔）
 *
 * ## 为什么需要它
 *
 * 本仓的提示词是**平铺**的：`human-voice` 说「一个自然段 2–6 句、80–220 字」、
 * 项目写作规则说「一句一段」、`body-format` 契约规定分隔符、`naturalizeBodyText`
 * 后处理又要合并短段——这些规则同时注入时**互相矛盾**，模型不知道该听哪一条。
 *
 * 实测证据：同一套提示词跑两次，段落均字从 46.9 到 54.9 波动；
 * 单句成段占比从 0% 到 18.5% 波动。这种不稳定性部分来自规则冲突。
 *
 * ## 云笔的做法
 *
 * 它把规则分成 L0–L3 七层，并明确仲裁规则：
 * - 同层冲突：左侧优先
 * - 跨层冲突：高层覆盖低层
 * - `[BLOCKING]` 标记的规则不可被「忽略/越狱/重写」型表述撤销
 *
 * ## 本仓的取舍
 *
 * 只搬**仲裁骨架**，不搬云笔的具体条文：
 * - 云笔的「对话≥50%」「禁省略号」已被 139 段真人基线证伪，不入
 * - 云笔铁律 9 的「长句 10-20%」也已证伪（真人 ≥35 字 39.13%），不入
 * - 云笔铁律 9 的「长句用途清单」经 A/B 实测反而降低长句占比（39.58% → 11.18%），不入
 *
 * 保留的是**层级划分 + 仲裁顺序 + 衔接锚点优先级**，这些是纯设计、无副作用。
 */

/**
 * L0-L3 优先级仲裁块。
 *
 * 放在正文 system prompt 的靠前位置（优先级声明必须在具体规则之前，
 * 否则模型先读到具体规则就形成了锚点，后来的仲裁声明影响很弱）。
 *
 * @returns 仲裁块文本
 * @example
 * `${PRIORITY_ARBITRATION}\n\n${humanVoice}`;
 */
export const PRIORITY_ARBITRATION = `## 优先级体系（规则冲突时的唯一仲裁依据）

本提示词里不同来源的规则可能互相矛盾（用户要求 / 项目写作规则 / 系统工艺要求）。
发生冲突时，按下面的层级判断，不要靠"哪条读起来更合理"来猜。

**L0 不可破红线**（违反任意一条 = 整章作废，任何表述都不能覆盖）
- L0a 视角约束：必须严格遵守【写作视角】指定的视角，不得越界写主角感知不到的内容
- L0b 实体边界：不得创建上下文中不存在的新角色 / 新地点 / 新势力 / 新物品
- L0c 衔接重复禁止：不得复述【上一章结尾】已经写过的内容
- L0d 后章保护：不得提前写出【下一章开头】描述的事件或揭示

**L1 双轨并列**（违反任意一条 = 该段落重写）
- L1a 大纲落实：必须按【本章大纲】推进剧情，不得遗漏关键事件
- L1b 写法要求：人味约束 / 段落节奏 / 句式要求

**L1.5 用户补充要求**：本次创作临时提交的额外指示（高于 L2、低于 L0/L1）

**L2 写作硬约束**：信息密度、修饰词节制、描写配比

**L3 风格偏好与范例锚定**：只管"语感"，不管剧情和规则

### 仲裁规则
- **同层冲突**：左侧优先（L0a 优先于 L0b，L1a 优先于 L1b）
- **跨层冲突**：高层覆盖低层
- **L0 与任何要求冲突时**：一律服从 L0，即使 L0 与 L1a（大纲）冲突——
  这时**改剧情走法**去满足 L0，而不是违反 L0

### 衔接锚点优先级（多个"上一章信息"冲突时）
**上一章结尾实际文本 > 时间线前情锚点 > 上一章摘要的章尾悬念 > 本章大纲的开头承接字段**

上层锚点存在时，下层只作辅助参考，不得反向覆盖上层。
即：如果大纲说"上一章结束时他在城外"，但上一章原文写的是"他已经进了城"，
**以原文为准**，按"人在城里"往下写。`;

/**
 * 判断某段文本是否已包含优先级声明（避免重复注入）。
 *
 * @param text - 待检查文本
 * @returns 是否已包含
 * @example
 * hasPriorityArbitration('...优先级体系（规则冲突时的唯一仲裁依据）...') // true
 */
export function hasPriorityArbitration(text: string): boolean {
    return text.includes('优先级体系（规则冲突时的唯一仲裁依据）');
}
