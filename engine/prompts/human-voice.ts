/**
 * human-voice.ts — 正文/协同写作的人味与可读性约束
 *
 * 2026-10-27 调整：
 * 旧版用“每 10 句至少 3 句不超过 10 字”“允许单句成段”等配额，
 * 模型会把它执行成通篇短句 + 一句一段，反而形成新的 AI 腔。
 * 新版以自然段为单位，先保证人怎么读，再谈节奏。
 *
 * 2026-10-30 第三版：吸收「去AI味」实战规则（来源：云笔 AI 社区规则库
 * 的「去AI味润色」场景规则，经 251 章真实连载验证）——标点硬上限、
 * 排比感慨禁令、心理/景物行数上限、描写占比、章首承接与章末钩子。
 *
 * 这段约束放在写作规则之后注入，优先级高于项目模板里的“一句一段”。
 *
 * 2026-10-31 第四版（v4）：实测证明「数值配额 + 禁令」这条路走不通——
 * 模型逐条达标后产出的是「每项都刚好合格」的均匀文本，AI 感正来自这种均匀；
 * 而且项目里明明有真人样文（文笔风格模板.md 的《雪中悍刀行》3 段）却因为双文件
 * 陷阱没被读到。v4 改为「样文优先」：注入 2–3 段真人文本 + 6 条弱约束；
 * 旧配额版保留为 `HUMAN_VOICE_BLOCK`，可用设置 `humanVoiceMode='quota'` 回退对比。
 */

export const HUMAN_VOICE_BLOCK = `【人味与可读性（最高优先级，优先于写作规则中的“一句一段/一段一个句号”）】

一、分段
1. 以自然段为单位：一个自然段 2–6 句，约 80–220 字；一个自然段写成一行，段内不要换行。
2. 不要一句一段。只有强调、转折、单独的动作节拍或对话交锋，才允许一句话独立成段；每千字不超过 3 处。
3. 对话可以和说话人的动作、神态、心理放在同一段；连续对话按说话人分段，不要每句都另起一行。
4. 场景转换、时间跳跃才另起一段；不要把同一个动作拆成三四行。

二、句子
5. 句长要像真人说话：平均 20–30 字；35 字以上的长句占 10%–20%；10 字以下的短句不超过 25%。短句是调味，不是主菜。
6. 允许从句、插入语、补充说明和口语顺序；不要每句都写成“主语+动词+句号”的短镜头。
7. 连续 3 句不要用同一个主语开头；用名字、身份、代词、动作交替。

三、标点硬规则（检测器对这几种标点最敏感）
8. 不要用分号。中文小说里分号几乎只出现在 AI 文本里；需要断句就用句号。
9. 省略号全文最多 2 处；话没说完，写出「话被打断」的动作，不要打省略号。
10. 破折号全文最多 2 处；解释用冒号，声音拖长用描写，插入语用逗号。

四、句式禁令
11. 「不是A，而是B」「不是X。是Y。」这类先否定再肯定的句式，全篇最多 1 处；其余改成直接陈述。
12. 禁止排比式感慨：「他不知道……他只知道……」「她不明白……她只明白……」一段都不要有。
13. 禁止末段升华：不要用一句独立短段总结全文或点题（「这是关于……的故事」「有些人注定……」）。结尾落在动作、对话或悬念上。
14. 不写「不仅…而且」「既…又」这类对称句；不连续使用比喻。

五、内容配比
15. 心理描写一次不超过 3 行；纯景物描写一次不超过 3 行；描写（环境+外貌+心理独白）合计不超过全篇两成，其余交给对话和动作。
16. 情感通过动作和对话体现；角色的感受用一句话带过，不要替读者感慨。
17. 每个场景有 2–3 处关键身体感觉即可，不要每一段都打卡“身体感觉+情绪变化”。
18. 对话占 25%–45%；对话可以有停顿、打断、答非所问、口头禅、没话找话。

六、词汇要像真人
19. 允许重复用词、口语、一点方言和粗话；词汇过于“正确”、每段长短过于整齐，本身就是 AI 特征。
20. 允许解释、交代、过渡和一点废话；该告诉读者的信息就明说，不要什么都藏着。
21. 叙述者可以有人格：冷幽默、市井气、偏见、吐槽。不要每段都追求画面感和金句。

七、章首承接与章末钩子
22. 如果上下文给了【上一章结尾】：本章第一句必须承接它（延续其中的人物、动作或对话中的至少一个元素），不要时间硬切、不要另起炉灶。
23. 全章最后一句落在对话、动作或悬念上；不要落在纯景物描写或无意义的感叹（如「他叹了口气」「风吹过死域」）上。`;

export const HUMAN_VOICE_SHORT = `自然段 2–6 句、80–220 字，不要一句一段；句长平均 20–30 字，长句占 10%–20%，10 字以下短句不超过 25%；对话占 25%–45%；不用分号，省略号和破折号全文各最多 2 处；「不是A而是B」最多 1 处，禁止排比感慨和末段升华；心理和景物描写一次不超过 3 行；词汇允许口语和不完美；结尾落在动作、对话或悬念上。`;

/**
 * v4 弱约束（样文优先模式）。
 * 刻意不做数值配额：只描述「可观察的差异」，把节奏交给样文。
 */
export const HUMAN_VOICE_WEAK_RULES = `【人味要求（按这几条写，照着上面的样文找语感）】
1. 信息由人物说出来：每个场景至少 6–10 次对话来回，对话争取占到全文三分之一；不要用叙述者转述本该由角色说的话。
2. 叙述句长短混用：短句（≤10 字）用来跑节奏，但每隔几句要有一个能连着读下去的长句；不要整篇都是碎句。
3. 让人物说人话：口语、口头禅、抢话、打断、答非所问都可以，按人物身份决定粗不粗。
4. 用具体时间与序数定节拍：第几波、第几分钟、第几手、第几次——读者才跟得上。
5. 不写总结段、不写升华段；结尾落在动作、对话，或一句没说完的话上。
6. 如果给了【上一章结尾】，本章第一句从它的情境里接着写。`;

export interface HumanVoiceOptions {
    /** 'exemplar'（默认，样文优先）| 'quota'（旧版数值配额，回退对比用） */
    mode?: 'exemplar' | 'quota';
    /** 已选好的真人样文（由 style-exemplars 提供） */
    exemplarBlock?: string;
}

/**
 * 组装人味约束块。
 * - 样文优先模式：样文块 + 6 条弱约束；没有样文时只给弱约束（绝不再退回配额清单）。
 * - 配额模式：返回旧版 `HUMAN_VOICE_BLOCK`，用于 A/B 对比与回退。
 * @param options - 配置项
 * @returns 文本结果
 */
export function buildHumanVoiceBlock(options: HumanVoiceOptions = {}): string {
    if (options.mode === 'quota') return HUMAN_VOICE_BLOCK;
    const parts = [
        (options.exemplarBlock || '').trim(),
        HUMAN_VOICE_WEAK_RULES,
    ].filter(Boolean);
    return parts.join('\n\n');
}

